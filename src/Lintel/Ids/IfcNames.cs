using System;
using System.Collections.Generic;
using System.IO;
using System.Reflection;

namespace Lintel.Ids;

/// <summary>An IFC data type: its spelling, the XML base type of its values, and the SI unit IDS stores them in.</summary>
public sealed class IfcDataType
{
    public IfcDataType(string name, string xmlBase, string? unit)
    {
        Name = name;
        XmlBase = xmlBase;
        Unit = unit;
    }

    /// <summary>The name as the IFC documentation spells it, such as <c>IfcLengthMeasure</c>.</summary>
    public string Name { get; }

    /// <summary><c>xs:string</c>, <c>xs:double</c>, <c>xs:integer</c>, <c>xs:boolean</c>, ...; empty when IDS defines none.</summary>
    public string XmlBase { get; }

    /// <summary>The SI unit as Lintel writes it, such as <c>m</c> or <c>W/m2K</c>; <c>null</c> for a type without a unit.</summary>
    public string? Unit { get; }

    public bool IsNumeric => XmlBase == "xs:double" || XmlBase == "xs:integer";
}

/// <summary>
/// The spelling of IFC names. IDS writes them in upper case (IFCWALL); Lintel writes them as the IFC
/// documentation does (IfcWall). The tables are generated by tools/gen-ifc-names.py.
/// </summary>
public static class IfcNames
{
    private static readonly Lazy<Dictionary<string, string>> Classes = new(LoadClasses);
    private static readonly Lazy<Dictionary<string, IfcDataType>> DataTypes = new(LoadDataTypes);

    /// <summary>The class in the spelling of the IFC documentation, or the name as given when it is not known.</summary>
    public static string Class(string name) =>
        Classes.Value.TryGetValue(name.ToUpperInvariant(), out var spelled) ? spelled : name;

    /// <summary>The data type with this name in any case, or <c>null</c>.</summary>
    public static IfcDataType? DataType(string name) =>
        DataTypes.Value.TryGetValue(name.ToUpperInvariant(), out var type) ? type : null;

    private static Dictionary<string, string> LoadClasses()
    {
        var classes = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach (var line in ReadLines("ifc-classes.txt"))
        {
            classes[line.ToUpperInvariant()] = line;
        }

        return classes;
    }

    private static Dictionary<string, IfcDataType> LoadDataTypes()
    {
        var types = new Dictionary<string, IfcDataType>(StringComparer.Ordinal);
        foreach (var line in ReadLines("ifc-datatypes.tsv"))
        {
            var fields = line.Split('\t');
            var unit = fields.Length > 2 && fields[2].Length > 0 ? fields[2] : null;
            types[fields[0].ToUpperInvariant()] = new IfcDataType(fields[0], fields.Length > 1 ? fields[1] : string.Empty, unit);
        }

        return types;
    }

    private static IEnumerable<string> ReadLines(string file)
    {
        var assembly = typeof(IfcNames).GetTypeInfo().Assembly;
        using var stream = assembly.GetManifestResourceStream("Lintel.Ids.Data." + file)
            ?? throw new InvalidOperationException("The embedded table " + file + " is missing.");
        using var reader = new StreamReader(stream);
        string? line;
        while ((line = reader.ReadLine()) is not null)
        {
            if (line.Length > 0)
            {
                yield return line;
            }
        }
    }
}
